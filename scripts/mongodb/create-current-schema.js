const scalar = {
  string: { bsonType: 'string' },
  optionalString: { bsonType: ['string', 'null'] },
  date: { bsonType: 'date' },
  optionalDate: { bsonType: ['date', 'null'] },
  bool: { bsonType: 'bool' },
  optionalBool: { bsonType: ['bool', 'null'] },
  int: { bsonType: ['int', 'long'] },
  optionalInt: { bsonType: ['int', 'long', 'null'] },
  number: { bsonType: ['decimal', 'double', 'int', 'long'] },
  optionalNumber: { bsonType: ['decimal', 'double', 'int', 'long', 'null'] },
  object: { bsonType: 'object' },
  optionalObject: { bsonType: ['object', 'null'] },
  array: { bsonType: 'array' },
  optionalArray: { bsonType: ['array', 'null'] },
  value: {},
};

const s = scalar;

function schema(required, properties, idType = 'string') {
  return {
    $jsonSchema: {
      bsonType: 'object',
      required: ['_id', ...required],
      additionalProperties: true,
      properties: {
        _id: idType === 'int' ? s.int : s.string,
        ...properties,
      },
    },
  };
}

function collection(name, required, properties, options = {}) {
  return { name, validator: schema(required, properties, options.idType) };
}

function createOrUpdateCollection({ name, validator }) {
  if (db.getCollectionNames().includes(name)) {
    db.runCommand({ collMod: name, validator, validationLevel: 'moderate', validationAction: 'warn' });
    return;
  }

  db.createCollection(name, { validator, validationLevel: 'moderate', validationAction: 'warn' });
}

function createIndexSafe(collectionName, keys, options) {
  try {
    db.getCollection(collectionName).createIndex(keys, options);
  } catch (error) {
    printjson({ warning: 'createIndex failed', collection: collectionName, keys, options, error: error.message });
  }
}

